using System.Xml.Linq;
using FeedForge.Models;

namespace FeedForge.Formats;

/// <summary>
/// Google Merchant Center ürün feed'i (RSS 2.0 + g: namespace).
/// https://support.google.com/merchants/answer/7052112
/// </summary>
public class GoogleMerchantFormat : IFeedFormat
{
    public string Key => "google";
    public string DisplayName => "Google Merchant XML (RSS 2.0)";
    public string ContentType => "application/xml";

    private static readonly XNamespace G = "http://base.google.com/ns/1.0";

    public ParseResult Parse(string raw)
    {
        var result = new ParseResult();
        XDocument doc;
        try { doc = XDocument.Parse(raw); }
        catch (Exception ex)
        {
            result.Issues.Add(new ValidationIssue { Severity = "error", Message = "XML okunamadı: " + ex.Message });
            return result;
        }

        var items = doc.Descendants("item").ToList();
        if (items.Count == 0)
            result.Issues.Add(new ValidationIssue { Severity = "error", Message = "Feed içinde <item> bulunamadı. Google Merchant RSS formatı bekleniyor." });

        foreach (var item in items)
        {
            string V(string local) =>
                item.Element(G + local)?.Value?.Trim()
                ?? item.Element(local)?.Value?.Trim()
                ?? "";

            var p = new Product
            {
                Id = V("id"),
                Title = V("title"),
                Description = V("description"),
                Link = V("link"),
                ImageLink = V("image_link"),
                Brand = V("brand"),
                Gtin = V("gtin"),
                Mpn = V("mpn"),
                Category = V("google_product_category"),
                Condition = string.IsNullOrEmpty(V("condition")) ? "new" : V("condition"),
                Availability = ParseHelpers.NormalizeAvailability(V("availability"))
            };

            var (price, cur) = ParseHelpers.ParsePrice(V("price"));
            p.Price = price;
            if (cur != null) p.Currency = cur;

            var (sale, _) = ParseHelpers.ParsePrice(V("sale_price"));
            p.SalePrice = sale;

            foreach (var extra in item.Elements(G + "additional_image_link"))
                p.AdditionalImageLinks.Add(extra.Value.Trim());

            if (int.TryParse(V("quantity"), out var q)) p.StockQuantity = q;

            result.Products.Add(p);
        }
        return result;
    }

    public string Write(IEnumerable<Product> products)
    {
        var channel = new XElement("channel",
            new XElement("title", "Product Feed"),
            new XElement("link", "https://example.com"),
            new XElement("description", "Generated by FeedForge"));

        foreach (var p in products)
        {
            var item = new XElement("item",
                new XElement(G + "id", p.Id),
                new XElement("title", p.Title),
                new XElement("description", p.Description),
                new XElement("link", p.Link),
                new XElement(G + "image_link", p.ImageLink),
                new XElement(G + "availability", p.Availability.Replace("_", " ")),
                new XElement(G + "condition", p.Condition));

            if (p.Price.HasValue)
                item.Add(new XElement(G + "price", ParseHelpers.FormatPrice(p.Price.Value, p.Currency)));
            if (p.SalePrice.HasValue)
                item.Add(new XElement(G + "sale_price", ParseHelpers.FormatPrice(p.SalePrice.Value, p.Currency)));
            if (!string.IsNullOrEmpty(p.Brand)) item.Add(new XElement(G + "brand", p.Brand));
            if (!string.IsNullOrEmpty(p.Gtin)) item.Add(new XElement(G + "gtin", p.Gtin));
            if (!string.IsNullOrEmpty(p.Mpn)) item.Add(new XElement(G + "mpn", p.Mpn));
            if (!string.IsNullOrEmpty(p.Category)) item.Add(new XElement(G + "google_product_category", p.Category));
            foreach (var img in p.AdditionalImageLinks)
                item.Add(new XElement(G + "additional_image_link", img));

            channel.Add(item);
        }

        var doc = new XDocument(
            new XDeclaration("1.0", "utf-8", null),
            new XElement("rss",
                new XAttribute("version", "2.0"),
                new XAttribute(XNamespace.Xmlns + "g", G.NamespaceName),
                channel));

        return doc.Declaration + Environment.NewLine + doc.ToString();
    }
}
